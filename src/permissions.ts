/**
 * The permission codes for the screens this package ships.
 *
 * These live here rather than in each application because they describe THIS
 * package's screens: a fee structure, a requisition, a payout. Both products
 * talk to the same backend engines, so the codes are identical in both; keeping
 * two copies in step by hand is how one of them silently stops gating.
 *
 * A host merges these into its own table (see console-fe/src/permissions), so
 * application screens keep reading a single `P`.
 */

/**
 * Numbering. A code is MM RR AA: module, resource, action. Actions follow the
 * house table (01 view, 02 create, 03 update, and so on); the resources are:
 *
 *   Finance (20): 01 entity, 02 account, 03 period, 04 journal, 05 invoice,
 *   06 creditnote, 07 refund, 08 concession, 09 paymentplan, 10 dunning,
 *   11 directentry, 12 report, 13 currency, 14 fxrate, 15 taxcode,
 *   16 costcenter, 17 dimension, 18 bankaccount, 19 expenseclaim, 20 pettycash,
 *   21 tax, 22 payrollrun, 23 budget, 24 fixedasset, 25 audit, 26 customer,
 *   27 feestructure, 28 payment, 29 pettycashvoucher, 30 salary, 31 writeoff,
 *   32 settings; 33 entity, 34 account and 35 period hold the renumbered codes
 *   described below.
 *
 *   Procurement (70): 01 category, 02 vendor, 03 catalog_item, 04 contract,
 *   05 requisition, 06 rfq, 07 quotation, 08 purchase_order, 09 goods_receipt,
 *   10 vendor_invoice, 11 vendor_payment, 12 approval, 13 stock, 14 report,
 *   15 vendor_assessment, 16 settings, 17 competition, 18 analytics.
 *
 *   Payments (80): 01 collection, 02 virtual_account, 03 payout, 04 report,
 *   05 payout_batch, 06 webhook, 07 unattributed_webhook.
 *
 * Every code these modules use lives here and nowhere else; the host
 * applications spread this table into their own.
 */

