// Rewrite src/backend-key-catalogue.ts from the backend's own permission registry.
//
// The console menus and the permission codes in this package name backend keys,
// and nothing at runtime says when one of them names a key that does not exist:
// the screen just never appears, for everybody. The catalogue is the list the
// tests check them against, so it has to be the backend's list, not ours.
//
//   cd backend/apps && ../cx/bin/python manage.py show_access_registry --json \
//     | node ../../FinPro/sync-key-catalogue.mjs
//
// Run it whenever the backend adds, renames or retires a key in one of the
// modules below. A key it adds that no screen owns then fails
// console-nav.test.ts until a screen declares it.
import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";

const MODULES = ["finance", "payments", "procurement", "workflow", "platform"];

const here = dirname(new URL(import.meta.url).pathname);
const registry = JSON.parse(readFileSync(0, "utf8"));
const keys = registry.modules
  .filter((module) => MODULES.includes(module.key))
  .flatMap((module) => module.resources.flatMap((resource) => resource.permissions.map((p) => p.key)))
  .sort();

if (!keys.length) {
  console.error("No keys found. Pipe in `manage.py show_access_registry --json`.");
  process.exit(1);
}

const body = `/**
 * Every active backend permission key in the modules this package's screens
 * read, as the backend's access registry lists it. Generated by
 * sync-key-catalogue.mjs; do not edit by hand.
 *
 * The menus and permission codes are tested against this list, so a code that
 * names a key the backend does not have, or a key that no screen owns, fails a
 * test instead of silently hiding a screen.
 */
export const BACKEND_KEY_CATALOGUE: readonly string[] = [
${keys.map((key) => `  "${key}",`).join("\n")}
];
`;

writeFileSync(resolve(here, "src/backend-key-catalogue.ts"), body);
console.log(`Wrote ${keys.length} keys from ${MODULES.join(", ")}.`);
